def fix_text(t):
    t = re.sub(r'(?<!S)图(\d+)(?!\d)', lambda m: FIG[int(m.group(1))] if int(m.group(1)) in FIG else m.group(0), t)
    t = re.sub(r'(?<!S)表(\d+)(?!\d)', lambda m: TAB[int(m.group(1))] if int(m.group(1)) in TAB else m.group(0), t)
    t = re.sub(r'(?<=[（见、，；\s–])([4-8]\.\d)(?=[）、，；\s–])', lambda m: SEC.get(m.group(1), m.group(1)), t)
    return t.replace('附录 A', 'S2').replace('附录 B', 'S3').replace('附录 C', 'S4').replace('附录 D', 'S9').replace('附录 E', 'S7')


def fix(t):
    out = []
    for ln in t.split('\n'):
        m = re.match(r'^!\[图(\d+)　(.*)\]\((.+)\)\s*$', ln)
        if m:
            n = int(m.group(1))
            if FIG[n].startswith('S图'):
                k = FIG[n][2:]
                out.append(f'![{FIG[n]}　{fix_text(m.group(2))}](figures_chain_v6/补充/S图{int(k):02d}_{SFILE[n]}.png)')
            continue
        out.append(fix_text(ln))
    return '\n'.join(out)


