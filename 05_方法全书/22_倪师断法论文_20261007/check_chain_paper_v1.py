"""论文第七稿（推理链）核数与核引文 v1：只读，不改论文。
一、引文：正文里凡「……」（T编号）形式的原话，去掉空白后必须是该条讲稿原话的连续片段；中间有「……」的分段核。
二、数字：从 checks/chain_paper_counts_v1.json（只读登记过的结果）算出应有的写法，逐条核对正文里有这一写法。
三、附录 A：表里每一行的原话摘录，必须与推理链知识库里那一步的原话摘录完全相同。
四、图：正文引用的图文件都存在，图号、表号从 1 连续编号。
写出 <out>（文件已存在就停），并打印不合格的项。用法：python3 check_chain_paper_v1.py --paper <论文.md> --out <新文件>"""
import argparse, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
W5 = os.path.dirname(HERE)
CH = os.path.join(W5, '23_倪师推理链_20261007')
CORPUS = os.path.join(W5, '20_全书倪师全面比对_20261005', 'packets_v1', 'Q01', 'ni_corpus.txt')
norm = lambda s: re.sub(r'\s+', '', s or '')


def pct(x, d=1):
    return f'{x * 100:.{d}f}%'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--paper', required=True); ap.add_argument('--out', required=True)
    a = ap.parse_args()
    assert not os.path.exists(a.out)
    md = open(a.paper, encoding='utf-8').read()
    c = json.load(open(os.path.join(HERE, 'checks', 'chain_paper_counts_v1.json'), encoding='utf-8'))
    corpus = {}
    for ln in open(CORPUS, encoding='utf-8'):
        t = ln.rstrip('\n').split('｜')
        corpus[t[0]] = norm(t[4])
    res = {'引文': [], '数字': [], '附录A': [], '图表': []}
    # 一、引文
    for m in re.finditer(r'「([^「」]{4,})」[）\)]?\s*（(T\d+)[，、）]', md):
        q, T = m.group(1), m.group(2)
        parts = [p for p in re.split(r'……', q) if p.strip()]
        ok = T in corpus and all(norm(p) in corpus[T] for p in parts)
        res['引文'].append({'T': T, '引文': q[:40], 'ok': ok})
    # 二、数字
    E = c['抽取']; J = c['裁定']; K = c['核查']; N = c['归一']; B = c['知识库']; V = c['覆盖']; TR = c['可追溯']; M = c['主检验']; D = c['事后诊断']; S = c['讲述时段']; X = c['示例盘r30']
    lay = V['各层盘数']; n = V['盘数']
    assert abs(E['推理步有无一致'] / E['条目'] - E['一致比例']) < 1e-4 and abs(V['走到成败'] / n - V['比例·成败']) < 1e-4
    want = [
        ('条目', f"{E['条目']} 条"), ('甲抽出', f"甲抽出 {E['甲抽出']} 步"), ('乙抽出', f"乙抽出 {E['乙抽出']} 步"),
        ('按条一致', f"{E['推理步有无一致']} 条（{pct(E['推理步有无一致'] / E['条目'])}）"), ('甲乙都抽到', f"{E['定稿来源']['甲乙']} 步（{pct(E['定稿来源']['甲乙'] / J['定稿步'])}）"),
        ('只甲', f"只甲抽到的 {E['定稿来源']['只甲']} 步"), ('只乙', f"只乙抽到的 {E['定稿来源']['只乙']} 步"), ('补入', f"补入 {E['定稿来源']['补入']} 步"),
        ('定稿', f"定稿 {J['定稿步']} 步"), ('定性步数', f"定性步 {J['定性步']} 步"), ('推理步数', f"推理步 {J['推理步']} 步"),
        ('有步的条目', f"{J['有步的条目']} 条原话"), ('有推理步的条目', f"{J['有推理步的条目']} 条"), ('方法', f"{J['方法']} 条原话"),
        ('定性成立', f"判成立 {K['定性步成立']} 步（{pct(K['定性步成立'] / J['定性步'])}）"), ('推理成立', f"判成立 {K['推理步成立']} 步（{pct(K['推理步成立'] / J['推理步'])}）"),
        ('合计成立', f"{K['成立合计']} 步（{pct(K['成立合计'] / J['定稿步'])}）"), ('不成立', f"{K['不成立合计']} 步"),
        ('判断名', f"{N['判断名']} 个"), ('结点（归一）', f"{N['结点']} 个结点"), ('拆分', f"{N['拆成多个结点的判断名']} 个判断名"),
        ('全组一致率', pct(N['全组合并一致率'])), ('G3一致率', pct(N['合并一致率']['G3'])), ('G2一致率', pct(N['合并一致率']['G2'])),
        ('配对相同最低', f"{N['全部配对判断相同比例最低'] * 100:.1f}% 以上"),
        ('知识库步', f"{B['收下的步']} 步、{B['结点']} 个结点"), ('同义自推', f"有 {B['排除']['归一后同义自推']} 步"),
        ('引擎可用', f"定性步 {B['引擎可用的定性步']} 步，推理步 {B['引擎可用的推理步']} 步，共 {B['引擎可用']} 步"),
        ('不可操作', f"不可操作的 {B['不可操作']} 步"), ('命例特指全部', f"{B['命例特指·全部']} 步"), ('命例特指引擎', f"{B['命例特指·引擎可用']} 步"),
        ('命例特指推理步', f"推理步 {B['命例特指·引擎可用的推理步']} 步"), ('连线', f"{B['推理步连线']} 条连线"),
        ('表2先天', f"| 定性步 | {B['按类型适用']['定性步·先天']} | {B['按类型适用']['定性步·大限']} | {B['按类型适用']['定性步·流年']} | {B['按类型适用']['定性步·小限']} | {B['定性步']} |"),
        ('表2推理', f"| 推理步 | {B['按类型适用']['推理步·先天']} | {B['按类型适用']['推理步·大限']} | {B['按类型适用']['推理步·流年']} | {B['按类型适用']['推理步·小限']} | {B['推理步']} |"),
        ('非先天推理步', f"{B['按类型适用']['推理步·大限'] + B['按类型适用']['推理步·流年'] + B['按类型适用']['推理步·小限']} 条推理步"),
        ('定性→路线', f"定性 → 路线（{c['层间连线']['定性→路线']} 条）"), ('路线→成败', f"路线 → 成败（{c['层间连线']['路线→成败']} 条）"),
        ('定性→成败', f"定性 → 成败（{c['层间连线']['定性→成败']} 条）"), ('个性→行为', f"个性 → 行为只有 {c['层间连线']['个性→行为']} 条"),
        ('其余→其余', f"（{c['层间连线']['其余→其余']} 条）"), ('长相→成败', f"长相往后推的只有 {c['层间连线']['长相→成败']} 条"),
        ('覆盖任一层', f"{V['走到行为路线成败']} 张（{pct(V['走到行为路线成败'] / n)}）"), ('覆盖成败', f"{V['走到成败']} 张（{pct(V['走到成败'] / n)}）"),
        ('路线层', f"路线的 {pct(lay['路线'] / n)}"), ('行为层', f"行为 {pct(lay['行为'] / n)}"), ('个性层', f"个性 {pct(lay['个性'] / n)}"), ('长相层', f"长相只有 {pct(lay['长相'] / n)}"),
        ('推理步条数', f"中位数 {V['用上的推理步条数']['中位数']:g} 条（四分位 {V['用上的推理步条数']['下四分位']:g} 至 {V['用上的推理步条数']['上四分位']:g} 条），最多 {V['用上的推理步条数']['最大']} 条"),
        ('最长链', f"中位数 {V['最长链步数']['中位数']:g} 步（四分位 {V['最长链步数']['下四分位']:g} 至 {V['最长链步数']['上四分位']:g} 步），最多 {V['最长链步数']['最大']} 步"),
        ('经推理步', f"{pct(V['经推理步的结点']['合计'] / V['经推理步的结点']['结点合计'])} 至少要经过一步推理步"), ('两说盘', f"{V['有两说的盘']} 张（{pct(V['有两说的盘'] / n)}）"),
        ('两说中位', f"中位数 {V['两说处数']['中位数']:g} 处"),
        ('可追溯', f"{TR['counts']['结点']} 个判断、{TR['counts']['推法']} 种推法"),
        ('计入', f"计入 {M['人数']['计入']} 人"), ('不计入', f"{M['人数']['不计入（倪师判断集为空）']} 人在讲述时段内"),
        ('平均u', f"平均 u = {M['主检验']['平均u']:.3f}"), ('p', f"p = {M['主检验']['p_单侧']:.3f}"), ('中位u', f"中位数 {M['主检验']['u中位数']:g}"),
        ('u<0.5', f"{M['主检验']['u小于0.5的人数']} 人的 u 小于 0.5"), ('u<=0.05', f"只有 {M['主检验']['u不大于0.05的人数']} 人的 u 不大于 0.05"),
        ('定性步u', f"平均 u = {M['另报·只用定性步']['平均u']:.3f}，p = {M['另报·只用定性步']['p_单侧']:.3f}"),
        ('连线', f"共 {M['另报·推理步连线']['连线合计']} 条"), ('连线复现', f"只有 {M['另报·推理步连线']['本人盘复现']} 条（{pct(M['另报·推理步连线']['比例'])}）"),
        ('连线留出', f"平均复现 {pct(M['另报·推理步连线']['留出盘复现比例的平均（各人平均再平均）'])}"),
        ('判断集', f"{S['计入者判断集结点数']['最少']} 至 {S['计入者判断集结点数']['最多']} 个结点，合计 {S['计入者判断集结点数']['合计']} 个"),
        ('剔除', f"在 {S['计入者剔除的引擎步']['最少']} 至 {S['计入者剔除的引擎步']['最多']} 步之间，中位数 {S['计入者剔除的引擎步']['中位数']:g} 步"),
        ('时段条目', f"{S['条目']} 条里的 {S['落在任一人时段内的条目']} 条"), ('时段步', f"{S['知识库步']} 步里有 {S['落在任一人时段内的步']} 步"),
        ('结构可达', f"只有 {D['D1可达性']['结构上可达的结点']} 个（{pct(D['D1可达性']['结构上可达的结点'] / D['D1可达性']['倪师判断集结点合计'])}）"),
        ('实际可达', f"{D['D1可达性']['实际可达的结点']} 个（{pct(D['D1可达性']['实际可达的结点'] / D['D1可达性']['倪师判断集结点合计'])}）"),
        ('不可达', f"其余 {D['D1可达性']['倪师判断集结点合计'] - D['D1可达性']['结构上可达的结点']} 个"),
        ('可达人数', f"另外 {D['D2分组描述']['人数']} 人，平均 u 为 {D['D2分组描述']['平均u']:.3f}"),
        ('诊断步', f"{sum(D['D4构成']['步'].values())} 步"), ('可求值步', f"{D['D4构成']['步']['定性步·可操作·无格无其他'] + D['D4构成']['步']['推理步·可操作·无格无其他']} 步的条件都能求值"),
        ('含格', f"{D['D4构成']['步']['定性步·可操作·含格']} 步靠「格」"),
        ('没说盘面', f"{D['D4构成']['步']['定性步·不可操作·含其他'] + D['D4构成']['步']['推理步·不可操作·含其他']} 步原话没说出盘面"),
        ('不剔除本人', pct(D['D3不剔除']['本人盘得分平均'])), ('不剔除随机', pct(D['D3不剔除']['留出盘得分平均'])), ('不剔除u', f"平均 u 为 {D['D3不剔除']['平均u']:.3f}"),
        ('r30结点', f"命宫一共推出 {X['覆盖口径']['命宫结点']} 个判断，其中 {X['覆盖口径']['最短推法也要经过推理步的结点']} 个"),
        ('r30推理步', f"命宫用上的推理步有 {X['覆盖口径']['用上的推理步条数']} 条"), ('r30最长', f"最长链 {X['覆盖口径']['最长链步数']} 步"),
        ('r30两说', f"命宫有 {X['覆盖口径']['两说处数']} 处两说"), ('推理步占比', f"推理步只有 {B['推理步']} 步（{round(B['推理步'] / B['收下的步'] * 100)}%）"),
    ]
    for name, w in want:
        res['数字'].append({'项': name, '应写': w, 'ok': w in md})
    # 三、附录 A
    kb = json.load(open(os.path.join(CH, 'chain_kb_v1.json'), encoding='utf-8'))
    by_T = {}
    for s in kb['steps']:
        by_T.setdefault(s['T'], []).append(s['原话摘录'])
    sec = md.split('## 附录 A')[1].split('## 附录 B')[0]
    for row in re.findall(r'^\| (T\d+) \|.*\| 「(.+)」 \|$', sec, flags=re.M):
        res['附录A'].append({'T': row[0], 'ok': row[1] in by_T.get(row[0], [])})
    for s_ in c['附录·推理步样例']:
        res['附录A'].append({'T': s_['T'], '项': '样例在表里', 'ok': f"「{s_['原话摘录']}」" in sec})
    # 四、图表
    figs = re.findall(r'^!\[图(\d+)　[^\]]*\]\(([^)]+)\)', md, flags=re.M)
    res['图表'].append({'项': '图号连续', 'ok': [int(f[0]) for f in figs] == list(range(1, len(figs) + 1))})
    for k, f in figs:
        res['图表'].append({'项': f'图{k}文件', 'ok': os.path.exists(os.path.join(HERE, f))})
    tabs = [int(x) for x in re.findall(r'^\*\*表(\d+)　', md, flags=re.M)]
    res['图表'].append({'项': '表号', 'ok': sorted(tabs) == list(range(1, len(tabs) + 1)), '次序': tabs})
    refs = set(int(x) for x in re.findall(r'图(\d+)', re.sub(r'!\[.*?\]\(.*?\)', '', md)))
    res['图表'].append({'项': '正文提到的图都存在', 'ok': refs <= set(range(1, len(figs) + 1)), '提到': sorted(refs)})
    bad = {k: [x for x in v if not x['ok']] for k, v in res.items()}
    out = {'paper': os.path.basename(a.paper), '各项数目': {k: len(v) for k, v in res.items()}, '不合格': bad, '明细': res}
    open(a.out, 'x', encoding='utf-8').write(json.dumps(out, ensure_ascii=False, indent=1) + '\n')
    print(json.dumps({'各项数目': out['各项数目'], '不合格': bad}, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
