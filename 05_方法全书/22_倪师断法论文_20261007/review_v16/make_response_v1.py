"""第十六稿内审第三轮（最后一轮）的逐条处理表：从 r3_returns/W1–W2.json 读出每条意见，配上处理决定，写出 意见处理_v1.md。
处理之后的第十七稿（定稿）由 make_v17.py、make_supplement_v17.py、make_chain_figures_v9.py、build_paper_v3.py 生成，数字由 check_chain_paper_v12.py 逐项核对；此后不再送审。"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
D = {
 'W1': {1: ('采纳', 'S6.4 标题下注明「本节沿用第十三稿的讨论；结论性的措辞以正文 8.3 为准」，结尾改为「没有证明能推回……（主检验 p = 0.066）」。'),
        2: ('采纳', '关联性思维一段写明分母是「由盘面起步下的断事」，并注明给星定名的两成不在此列。'),
        3: ('采纳', '8.2 与表4「情」一行改为「义理一派里儒理、史事两路以人事说《易》」，与第二节一致。'),
        4: ('采纳', '关联性思维一段的「凭」改为「明说的依据／明说的理由」。'),
        5: ('采纳', '图脚本 v9 改图4 的纵向排法：每个判断尽量与它的前提同高，「先生不好」紧挨「个性强」，箭头不再斜穿「佐才」；引擎与 S图7 不变。')},
 'W2': {1: ('采纳', '摘要、英文摘要写明 1685 步里起步 1314、推理步 371；结论写明核查成立的 1687 步里起步 1314、推理步 373。'),
        2: ('采纳', '第五节「知识库」一段补「归一表里另有 56 个结点只出现在核查不成立的步里，不进知识库」。'),
        3: ('采纳', '同 W1-1。'),
        4: ('采纳', 'S5.5 写明第二次认本人的全部论断（本人、陪衬与他人真盘）都按闭合规则生成（m4f_build_v1.py 调用 infer_candidates_closed），对第一次的复核说明换规则不影响第一次的结果。'),
        5: ('部分采纳', '再查一次：作者在山东大学历史学院的成果列表写「《周易研究》2002.3」，参考文献补为 2002(3) 并注明期号出处；页码仍未核到。引文已与爱思想网转载本逐字核对；8.4 局限写明「引文据转载本核对，原刊页码未核」，S13.2 同记。'),
        6: ('采纳', 'S8 功效表后加一句：每格只模拟 300 次，有抽样误差，0.07 那一格在误差之内；另做的零假设校准（各 2000 次）都不超过 0.05。'),
        7: ('采纳', '7.4 末条改为「按适用分开的全表，以及起步的定名、断事与结论层的交叉计数」。')},
}
out = ['# 第十六稿内审第三轮（最后一轮）：意见与处理\n',
       '2 名审稿人（Claude Fable 5.1，经 API 批量接口各自独立调用，effort high）读第十六稿正文与补充材料的 PDF，并附第二轮的意见处理表。审稿说明见 `审稿说明_v1.md`，角度见 `审稿角度_v1.json`，原始交卷与审计见 `r3_returns/`。这一轮之后不再送审。\n']
tot = {}
for r in ('W1', 'W2'):
    d = json.load(open(os.path.join(HERE, 'r3_returns', f'{r}.json'), encoding='utf-8'))
    assert set(D[r]) == {q['编号'] for q in d['问题']}, r
    out.append(f"\n## {r}　{d['角度']}（{d['分数']} 分）\n\n总体判断：{d['总体判断']}\n\n| 编号 | 级别 | 位置 | 意见（摘要） | 处理 | 怎么改 |\n|---|---|---|---|---|---|\n")
    for q in d['问题']:
        dec, how = D[r][q['编号']]
        tot[dec] = tot.get(dec, 0) + 1
        brief = q['问题'].replace('|', '／').replace('\n', ' ')
        brief = brief if len(brief) <= 70 else brief[:70] + '……'
        out.append(f"| {q['编号']} | {q['级别']} | {q['位置'].replace('|', '／')} | {brief} | {dec} | {how} |\n")
out.insert(2, '\n共 ' + str(sum(tot.values())) + ' 条：' + '，'.join(f'{k} {v} 条' for k, v in sorted(tot.items(), key=lambda kv: -kv[1])) + '。\n')
open(os.path.join(HERE, '意见处理_v1.md'), 'x', encoding='utf-8').write(''.join(out))
print(tot)
