"""第十八稿（投稿版）的用词替换表：把口语词换成书面说法，不动任何数字。
正文（论文正文_v18.md）、补充材料（make_supplement_v18.py）与核数脚本（check_chain_paper_v13.py）共用这一张表，
核数时把每条「应写」照同一张表替换后再到稿子里找，所以替换不会让核对漏掉数字。按次序替换（长的、特指的在前）。"""

VOCAB = [
    ('瞎猜期望', '随机期望'),
    ('瞎猜认对的机会是四分之一', '随机猜中的机会是四分之一'),
    ('多于瞎猜', '多于随机水平'),
    ('高于瞎猜', '高于随机水平'),
    ('（瞎猜是 2.5 位）', '（随机水平是 2.5 位）'),
    ('（瞎猜 1/4）', '（随机水平 1/4）'),
    ('瞎猜 7 题', '随机期望 7 题'),
    ('瞎猜 0.25', '随机水平 0.25'),
    ('写入文件交卷', '写入文件提交答卷'),
    ('交卷', '答卷'),
    ('平均 u 碰巧不大于实测值的比例', '平均 u 不大于实测值的比例'),
    ('碰巧', '偶然'),
    ('引擎在随机盘上推得动推不动？', '引擎在随机盘上能不能推下去？'),
    ('推理链推得动', '推理链推得下去'),
    ('专门找茬', '专门挑错'),
    ('找茬', '审查'),
    ('越拿不准', '越不确定'),
    ('拿不准的不合并', '没有把握的不合并'),
    ('也照出了它的样子', '也显出了它的样貌'),
]
GONE = ('瞎猜', '交卷', '碰巧', '推得动', '找茬', '拿不准', '照出')


def fix(s):
    for a, b in VOCAB:
        s = s.replace(a, b)
    return s


def assert_clean(s, where):
    left = [w for w in GONE if w in s]
    assert not left, (where, left)
