"""补充材料第十八稿（投稿版）：在第十七稿补充材料（补充材料_v17.md）上只做表述层面的改动，数字一个不动：
- 标题下加作者行；开头一句改指第十八稿；S1 标题「名词白话」改「术语说明」，与正文一致；
- S4.2 审稿记录末尾补一句，写明第十八稿改了什么、没改什么；
- 按 vocab_v18.VOCAB 把口语词换成书面说法（与正文、核数脚本共用同一张表）；S4.2 补的那一句有意写出旧词，放在替换之后。
每一处替换的原句必须恰好出现一次（否则停）；替换后不许再有表里的口语词。写出 补充材料_v18.md（已存在就停）。
用法：python3 make_supplement_v18.py"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from vocab_v18 import fix, assert_clean

s = open(os.path.join(HERE, '补充材料_v17.md'), encoding='utf-8').read()


def rep(a, b, n=1):
    global s
    assert s.count(a) == n, (s.count(a), a[:80])
    s = s.replace(a, b)


rep('# 从讲述到推理链：补充材料\n', '# 从讲述到推理链：补充材料\n\n于仁坪（独立研究者）\n')
rep('本补充材料随第十七稿一同发布。凡标「S」的节、图、表都在本文件里；「正文」指第十七稿正文。',
    '本补充材料随正文第十八稿（投稿版）一同发布。凡标「S」的节、图、表都在本文件里；「正文」指第十八稿正文。')
rep('## S1　名词白话（全表）', '## S1　术语说明（全表）')
s = fix(s)
assert_clean(s, '补充材料')
# 这一句有意写出被换掉的旧词，所以放在用词替换与检查之后
rep('据此改出第十七稿定稿，此后不再送审。',
    '据此改出第十七稿定稿，此后不再送审。第十八稿是投稿版：正文的条目改写成连贯段落，少数口语词改用书面说法（如「瞎猜」改「随机水平」或「随机期望」，'
    '「交卷」改「答卷」），参考文献改按 GB/T 7714—2015 著者-出版年制著录，并填写作者与公开地址；数字与结论都没有改，仍由同一套核数脚本逐项核对。')
open(os.path.join(HERE, '补充材料_v18.md'), 'x', encoding='utf-8').write(s)
print('已写出 补充材料_v18.md，字数', len(s))
